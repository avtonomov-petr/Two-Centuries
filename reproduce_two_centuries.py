# 3. Спектральный аудит и бутстрэп-интервалы (Таблица 1)
def full_audit(df_in, name_col, feat_cols, label):
    X = df_in[feat_cols].to_numpy(dtype=float)
    Z = (X - np.mean(X, axis=0)) / np.std(X, axis=0, ddof=1)
    N_obs, K_obs = Z.shape
    U, s, Vt = np.linalg.svd(Z, full_matrices=False)
    u1, u2 = np.take(U, 0, axis=1), np.take(U, 1, axis=1)
    v1, v2 = np.take(Vt, 0, axis=0), np.take(Vt, 1, axis=0)
    if v1.item(0) < 0:
        u1, v1 = -u1, -v1
    if v2.item(2) < 0:
        u2, v2 = -u2, -v2
    var1 = (s.item(0)**2) / np.sum(s**2) * 100.0
    var2 = (s.item(1)**2) / np.sum(s**2) * 100.0
    pr_u = (1.0 / np.sum(u1**4) - 1.0) / (N_obs - 1.0)
    pr_v = (1.0 / np.sum(v1**4) - 1.0) / (K_obs - 1.0)

    rng = np.random.default_rng(42)
    sub_n = int(np.floor(N_obs * 0.8))
    bu = []
    for _ in range(300):
        idx = np.sort(rng.choice(N_obs, size=sub_n, replace=False))
        Xb = X[idx, :]
        Zb = (Xb - np.mean(Xb, axis=0)) / np.std(Xb, axis=0, ddof=1)
        Ub, _, _ = np.linalg.svd(Zb, full_matrices=False)
        u1b = np.take(Ub, 0, axis=1)
        bu.append((1.0 / np.sum(u1b**4) - 1.0) / (sub_n - 1.0))

    en = pd.Series((u1**2)*100.0, index=df_in[name_col]).sort_values(ascending=False)
    print(f"{label:<32} | N={N_obs:2d} | Var1={var1:4.1f}% | PR_reg={pr_u:.3f} [{np.percentile(bu, 2.5):.3f}, {np.percentile(bu, 97.5):.3f}] | PR_feat={pr_v:.3f} | Top2={en.head(2).sum():.1f}%")
    return u1, u2, var1, var2, pr_u, pr_v

